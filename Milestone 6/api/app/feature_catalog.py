"""Builds the /model/features catalog from the frozen 86-feature contract.

Source of truth: ``daily_pipeline/utils/contracts/champion_86_features.json``
(``feature_prune.kept_features``) -- the exact columns the champion model
was trained and is scored on (see Milestone 5/metrics_summary.json).

For each feature we report:

- ``displayName`` / ``unit`` / ``source`` -- derived from the real ERA5 /
  Sentinel-2 / Sentinel-5P / SRTM-DEM variable each key names (standard
  physical units for those products; no invented labels).
- ``min`` / ``max`` / ``defaultValue`` -- populated only when we have a real
  basis for them: either (a) a mathematical identity (sin/cos terms are
  exactly bounded to [-1, 1]; percentages/fractions are bounded to their
  definition), or (b) empirical stats computed from the static DEM grid that
  ships with the repo (``era5_grid_dem_features.parquet``). Every other
  feature (live ERA5 weather, Sentinel EO, engineered fire-neighbor context)
  legitimately depends on the daily pipeline's live feature pull, which this
  offline catalog does not have -- those bounds are left ``null`` rather
  than guessed. A future iteration can populate them from a real historical
  feature summary once one is generated by the pipeline.
- ``editableInScenario`` -- False for static/structural/calendar features
  (terrain, lat/lon, day-of-year/month encodings) that a "what-if" scenario
  cannot meaningfully move; True for the dynamic weather/vegetation/
  satellite/fire-context features scenario controls are meant to perturb.
"""

