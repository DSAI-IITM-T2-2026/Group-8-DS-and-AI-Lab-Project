_S2_BAND_NAMES = {"B2": "Blue", "B3": "Green", "B4": "Red", "B8": "NIR", "B11": "SWIR1", "B12": "SWIR2"}


def _display_name(key: str) -> str:
    if key in _DISPLAY_OVERRIDES:
        return _DISPLAY_OVERRIDES[key]
    for band, label in _S2_BAND_NAMES.items():
        if key == f"s2n_{band}_mean":
            return f"Sentinel-2 {label} ({band}, mean)"
        if key == f"s2n_{band}_std":
            return f"Sentinel-2 {label} ({band}, std dev)"
    if key.startswith("fire_"):
        return key.replace("_", " ").replace("lag2", "(2-day lag)").title()
    for suffix, label in (
        ("_max_14d", " Max (14-day)"),
        ("_max_30d", " Max (30-day)"),
        ("_min_14d", " Min (14-day)"),
        ("_min_30d", " Min (30-day)"),
        ("_mean_14d", " Mean (14-day)"),
        ("_mean_30d", " Mean (30-day)"),
        ("_sum_14d", " Sum (14-day)"),
        ("_sum_30d", " Sum (30-day)"),
        ("_anomaly_30d", " Anomaly (30-day)"),
    ):
        if key.endswith(suffix):
            base = key[: -len(suffix)]
            return f"{_DISPLAY_OVERRIDES.get(base, base.replace('_', ' ').title())}{label}"
    return key.replace("_", " ").title()


def _source(key: str) -> str:
    if key.startswith(("t2m_", "d2m_", "sp_", "wind_", "swvl", "soil_", "cvh_", "cvl_", "lai_", "blh_", "i10fg_", "tp_", "rh_", "vpd_")):
        return SOURCE_ERA5
    if key.startswith("s2n_"):
        return SOURCE_SENTINEL2
    if key.startswith("s5n_"):
        return SOURCE_SENTINEL5P
    if key.startswith("fire_"):
        return SOURCE_FIRE_CONTEXT
    if key in {"elevation", "slope", "aspect_sin", "aspect_cos", "tri", "tpi", "orographic_index", "hillshade"}:
        return SOURCE_DEM
    if key in {"latitude", "longitude"}:
        return SOURCE_DEM
    if key in {"day_of_year_sin", "day_of_year_cos", "month_sin", "month_cos"}:
        return SOURCE_CALENDAR
    return SOURCE_ENGINEERED


def _unit(key: str) -> str | None:
    if key.startswith("t2m_") or key.startswith("d2m_"):
        return "K"
    if key.startswith("sp_"):
        return "Pa"
    if key.startswith("swvl"):
        return "m3/m3"
    if key.startswith("tp_"):
        return "mm"
    if key.startswith(("wind_speed", "i10fg_")):
        return "m/s"
    if key.startswith("rh_"):
        return "%"
    if key.startswith("vpd_"):
        return "kPa"
    if key.startswith("blh_"):
        return "m"
    if key.startswith(("cvh_", "cvl_")):
        return "fraction"
    if key.startswith(("lai_",)):
        return "m2/m2"
    if key == "elevation":
        return "m"
    if key == "slope":
        return "deg"
    if key in {"latitude", "longitude"}:
        return "deg"
    if key == "s2n_cloud_percentage":
        return "%"
    if key == "s2n_valid_fraction":
        return "fraction"
    if key.startswith("s5n_s5p_co"):
        return "mol/m2"
    if key.startswith("fire_") and "count" in key:
        return "cells"
    return None


def _bounds(key: str, dem_stats: dict[str, tuple[float, float, float]]) -> tuple[float | None, float | None, float | None]:
    """Returns (min, max, default) or (None, None, None) when unknown."""
    if key in _UNIT_CIRCLE_BOUNDED:
        return (-1.0, 1.0, 0.0)
    if key in _PERCENT_BOUNDED:
        lo, hi = _PERCENT_BOUNDED[key]
        return (lo, hi, 0.0)
    if key in _FRACTION_BOUNDED:
        lo, hi = _FRACTION_BOUNDED[key]
        return (lo, hi, 1.0)
    if key in _NONNEGATIVE_COUNTS:
        return (0.0, None, 0.0)
    if key in dem_stats:
        lo, hi, mean = dem_stats[key]
        return (lo, hi, mean)
    return (None, None, None)


def _step_for(lo: float | None, hi: float | None) -> float | None:
    if lo is None or hi is None:
        return None
    span = hi - lo
    if span <= 0:
        return None
    # A round-ish increment: ~1% of the real observed range.
    raw = span / 100
    return round(raw, 4) if raw < 1 else round(raw, 2)


@lru_cache(maxsize=1)
def _dem_stats() -> dict[str, tuple[float, float, float]]:
    ensure_pipeline_on_path()
    from paths import resolve_path

    cfg = get_pipeline_config()
    path = resolve_path(cfg, "dem_local")
    if not path.is_file():
        return {}
    frame = pd.read_parquet(path)
    stats: dict[str, tuple[float, float, float]] = {}
    for col in ("elevation", "slope", "tri", "tpi", "hillshade", "latitude", "longitude"):
        if col in frame.columns:
            series = frame[col].astype(float)
            stats[col] = (float(series.min()), float(series.max()), float(series.mean()))
    return stats


def build_feature_catalog() -> list[dict[str, Any]]:
    contract = get_feature_contract()
    dem_stats = _dem_stats()
    keys = contract["feature_prune"]["kept_features"]
    catalog: list[dict[str, Any]] = []
    for key in keys:
        lo, hi, default = _bounds(key, dem_stats)
        catalog.append(
            {
                "key": key,
                "display_name": _display_name(key),
                "type": "number",
                "unit": _unit(key),
                "source": _source(key),
                "min": lo,
                "max": hi,
                "step": _step_for(lo, hi),
                "default_value": default,
                "editable_in_scenario": key not in _NOT_EDITABLE,
            }
        )
    return catalog
